import turtle
screen = turtle.Screen()
screen.title("Turtle House Art")
t = turtle.Turtle()
t.pendown()
for _ in range(4):
    t.forward(100)
    t.right(90)
t.penup()
t.pendown()
t.left(60)
for _ in range(2):
    t.forward(100)
    t.right(120)
t.penup()
t.goto(20, -30)
t.setheading(0)
t.pendown()
for _ in range(4):
    t.forward(20)
    t.right(90)
t.penup()
t.goto(60, -30)
t.setheading(0)
t.pendown()
for _ in range(4):
    t.forward(20)
    t.right(90)
t.penup()
t.goto(40, -100)
t.setheading(90)
t.pendown()
t.forward(40)
t.right(90)
t.forward(20)
t.right(90)
t.forward(40)
t.penup()
turtle.done()